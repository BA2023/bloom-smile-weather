const reverse = new Map(Object.entries(english).map(([zh, en]) => [en, zh]));
const textState = new WeakMap(), attributeState = new WeakMap();
let language = 'zh';

function patternToEnglish(value) {
  let match = value.match(/^([\d.]+K?) 点赞$/);
  if (match) return `${match[1]} likes`;
  match = value.match(/^送出(.+)$/);
  if (match) return `Sent ${translate(match[1], 'en')}`;
  match = value.match(/^再送一次流光烟花，当前连送(\d+)次$/);
  if (match) return `Send Glow Fireworks again, ${match[1]} sent`;
  match = value.match(/^为模拟直播点赞，当前(\d+)次$/);
  if (match) return `Like this demo LIVE, ${match[1]} likes`;
  match = value.match(/^(.+)星焰，正在绽放$/);
  if (match) return `${translate(match[1], 'en')} fireworks are blooming`;
  return value;
}

export function translate(value, target = language) {
  const text = String(value), match = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const core = match[2];
  if (!core) return text;
  const source = reverse.get(core) ?? core;
  return match[1] + (target === 'en' ? (english[source] ?? patternToEnglish(source)) : source) + match[3];
}

function ignored(node) {
  const element = node.nodeType === 1 ? node : node.parentElement;
  return Boolean(element?.closest?.('[data-i18n-ignore], script, style'));
}

function translateText(node) {
  if (ignored(node)) return;
  const current = node.nodeValue, saved = textState.get(node);
  const source = saved && current === saved.rendered ? saved.source : translate(current, 'zh');
  const rendered = translate(source);
  textState.set(node, { source, rendered });
  if (current !== rendered) node.nodeValue = rendered;
}

function translateAttributes(element) {
  if (ignored(element)) return;
  const saved = attributeState.get(element) || {};
  for (const name of ['aria-label', 'placeholder', 'alt', 'title', 'content']) {
    if (!element.hasAttribute(name) || (name === 'content' && element.getAttribute('name') !== 'description')) continue;
    const current = element.getAttribute(name), previous = saved[name];
    const source = previous && current === previous.rendered ? previous.source : translate(current, 'zh');
    const rendered = translate(source); saved[name] = { source, rendered };
    if (current !== rendered) element.setAttribute(name, rendered);
  }
  attributeState.set(element, saved);
}

function translateTree(root) {
  if (root.nodeType === 3) { translateText(root); return; }
  if (root.nodeType !== 1 && root.nodeType !== 9 && root.nodeType !== 11) return;
  if (root.nodeType === 1) translateAttributes(root);
  root.querySelectorAll?.('[aria-label], [placeholder], [alt], [title], meta[name="description"]').forEach(translateAttributes);
  const walker = document.createTreeWalker(root, 4);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) translateText(node);
}

export function setLanguage(next, { persist = true } = {}) {
  language = next === 'en' ? 'en' : 'zh';
  if (persist) { try { localStorage.setItem('bloom-language', language); } catch {} }
  if (typeof document === 'undefined' || !document.createTreeWalker) return;
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
  translateTree(document.documentElement);
  for (const id of ['language-toggle', 'language-toggle-mobile']) {
    const button = document.getElementById(id);
    if (!button) continue;
    button.dataset.language = language;
    button.setAttribute('aria-label', language === 'zh' ? 'Switch to English' : '切换为中文');
  }
}

export function initLanguage() {
  if (typeof document === 'undefined' || !document.createTreeWalker) return;
  let stored = null; try { stored = localStorage.getItem('bloom-language'); } catch {}
  setLanguage(stored, { persist: false });
  for (const id of ['language-toggle', 'language-toggle-mobile']) {
    document.getElementById(id)?.addEventListener('click', () => setLanguage(language === 'zh' ? 'en' : 'zh'));
  }
  const observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'characterData') translateText(record.target);
      else if (record.type === 'attributes') translateAttributes(record.target);
      else for (const node of record.addedNodes) translateTree(node);
    }
  });
  observer.observe(document.documentElement, { subtree: true, childList: true, characterData: true,
    attributes: true, attributeFilter: ['aria-label', 'placeholder', 'alt', 'title', 'content'] });
}
